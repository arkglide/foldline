import fs from 'node:fs/promises';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { ensureEngine, ENGINE_COMMIT } from './engine.mjs';
import { l01Project } from '../game/project.mjs';
import { loadVoiceAssets } from './voice-assets.mjs';
import { feedbackAssets } from './feedback-assets.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const engine = await ensureEngine();
const synced = spawnSync(process.execPath, ['scripts/sync-runtime.mjs'], { cwd: engine, stdio: 'inherit' });
if (synced.status !== 0) throw Error('ArkGlide runtime synchronization failed.');
const { createServer } = await import(pathToFileURL(path.join(engine, 'node_modules/vite/dist/node/index.js')));
const compiler = await createServer({ root: engine, server: { middlewareMode: true, hmr: false, ws: false },
  appType: 'custom', optimizeDeps: { noDiscovery: true, include: [] } });
let project, projectAudio, voiceReport;
try {
  const { normalizeProject } = await compiler.ssrLoadModule('/src/utils/projectValidation.ts');
  const source = await l01Project();
  const data = JSON.parse(await fs.readFile(path.join(root, 'game/data/l01-dialogue.json'), 'utf8'));
  const voice = await loadVoiceAssets(data), feedback = await feedbackAssets();
  source.content.audio = [...voice.assets, ...feedback.assets];
  // The standalone runtime streams unused resources; these short cues must be
  // ready before script onStart/audio.list, including locally generated voices.
  source.settings.build.preload = source.content.audio.map(asset => `audio:${asset.id}`);
  project = normalizeProject(source);
  projectAudio = new Map([...voice.buffers, ...feedback.buffers]);
  voiceReport = voice.report;
} finally { await compiler.close(); }
const { RUNTIME_FILES, createStaticGame } = await import(pathToFileURL(path.join(engine, 'src/export/static-game.mjs')));
const runtime = Object.fromEntries(await Promise.all(RUNTIME_FILES.map(async name => [name,
  new Uint8Array(await fs.readFile(path.join(engine, 'public', name)))])));
const game = createStaticGame(project, { models: new Map(), textures: new Map(), audio: projectAudio }, runtime);
const output = path.join(root, '.generated/l01');
// This directory is solely generated by this script; source/checkouts are never removed.
await fs.rm(output, { recursive: true, force: true });
for (const [name, raw] of Object.entries(game.files)) {
  const target = path.join(output, name);
  await fs.mkdir(path.dirname(target), { recursive: true });
  await fs.writeFile(target, raw);
}
await fs.writeFile(path.join(root, '.generated/l01.project.json'), JSON.stringify(project, null, 2) + '\n');
await fs.writeFile(path.join(output, 'foldline-build.json'), JSON.stringify({
  level: 'C01-L01', stage: 'M1-greybox', engineCommit: ENGINE_COMMIT,
  revision: 'M1-R2', voiceLanguage: 'en', subtitleLanguages: ['zh-CN', 'en'], voice: voiceReport,
}, null, 2) + '\n');
console.log(`C01-L01: ${project.scene.nodes.length} nodes; native ArkGlide ${ENGINE_COMMIT.slice(0, 12)}; ${output}`);
console.log(`WinTTS voices: ${voiceReport.generated.length} available, ${voiceReport.missing.length} pending; 4 original mechanical cues.`);
// Deliberately never call game.zip(): the deliverable is source + HTTP runtime.
